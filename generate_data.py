"""
Generate a FAKE conference registration dataset for practice.

No real people or real contact data are used. Every name and email
is randomly generated by the Faker library.

Run:  python generate_data.py
Output: data/registrations_raw.csv
"""

import random
from datetime import date, timedelta
from pathlib import Path

import pandas as pd
from faker import Faker

SEED = 42
random.seed(SEED)
fake = Faker()
Faker.seed(SEED)

# --- Settings you can change -------------------------------------------------
EDITIONS = {
    # edition year: (city, event start date, number of registrations)
    2025: ("San Francisco, CA", date(2025, 11, 3), 900),
    2026: ("Boston, MA", date(2026, 11, 2), 1300),
}

TRACKS = [
    "Generative AI",
    "Machine Learning Foundations",
    "Computer Vision",
    "Natural Language Processing",
    "Agentic AI & Autonomous Systems",
    "AI in Healthcare",
    "Responsible & Ethical AI",
    "Reinforcement Learning",
]

COUNTRIES = {  # country: weight (how common it is)
    "United States": 35, "India": 14, "United Kingdom": 7, "Germany": 6,
    "Canada": 6, "China": 5, "Japan": 4, "Australia": 4, "France": 4,
    "South Korea": 3, "Singapore": 3, "Brazil": 2, "UAE": 2, "Netherlands": 3,
    "Italy": 2,
}

REG_TYPES = {"Delegate": 50, "Speaker": 15, "Poster Presenter": 15,
             "Student": 12, "Virtual": 8}
AFFILIATIONS = {"Academic": 55, "Industry": 35, "Government / Non-profit": 10}


def weighted(choices: dict) -> str:
    return random.choices(list(choices), weights=list(choices.values()))[0]


def registration_date(event_start: date) -> date:
    """Most people register in the last ~4 months before the event."""
    days_before = int(random.triangular(1, 300, 25))
    return event_start - timedelta(days=days_before)


def make_rows() -> list[dict]:
    rows, reg_no = [], 1
    for year, (city, start, count) in EDITIONS.items():
        for _ in range(count):
            first, last = fake.first_name(), fake.last_name()
            rows.append({
                "registration_id": f"NXT{year}-{reg_no:05d}",
                "edition": year,
                "city": city,
                "first_name": first,
                "last_name": last,
                "email": f"{first}.{last}{random.randint(1, 99)}@example.com".lower(),
                "country": weighted(COUNTRIES),
                "affiliation_type": weighted(AFFILIATIONS),
                "registration_type": weighted(REG_TYPES),
                "track": random.choice(TRACKS),
                "registration_date": registration_date(start).isoformat(),
                "attended": random.random() < 0.88,
            })
            reg_no += 1
    return rows


def add_mess(df: pd.DataFrame) -> pd.DataFrame:
    """Add realistic data problems so Week 2 has something to clean."""
    n = len(df)
    # 1) Duplicate registrations (~2%)
    dupes = df.sample(frac=0.02, random_state=SEED)
    df = pd.concat([df, dupes], ignore_index=True)
    # 2) Missing countries (~1.5%)
    df.loc[df.sample(frac=0.015, random_state=1).index, "country"] = None
    # 3) Inconsistent text: extra spaces and wrong case
    idx = df.sample(frac=0.03, random_state=2).index
    df.loc[idx, "country"] = df.loc[idx, "country"].str.upper() + "  "
    idx = df.sample(frac=0.02, random_state=3).index
    df.loc[idx, "track"] = df.loc[idx, "track"].str.lower()
    # 4) Country written differently
    us_idx = df[df["country"] == "United States"].sample(frac=0.05, random_state=4).index
    df.loc[us_idx, "country"] = "USA"
    # 5) A few broken emails
    idx = df.sample(n=max(5, n // 200), random_state=5).index
    df.loc[idx, "email"] = df.loc[idx, "email"].str.replace("@", "", regex=False)
    # Shuffle rows so problems are spread out
    return df.sample(frac=1, random_state=SEED).reset_index(drop=True)


def main() -> None:
    df = add_mess(pd.DataFrame(make_rows()))
    out = Path("data")
    out.mkdir(exist_ok=True)
    df.to_csv(out / "registrations_raw.csv", index=False)
    print(f"Saved {len(df):,} rows to {out / 'registrations_raw.csv'}")


if __name__ == "__main__":
    main()
